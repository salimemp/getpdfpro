#!/usr/bin/env node
/**
 * Pre-build step: read apps/web/content/blog/*.json and write a single
 * TypeScript module (apps/web/lib/blog-generated-posts.ts) that exports
 * the posts as an inlined constant array.
 *
 * Why this exists:
 *   Cloudflare Workers (the OpenNext target) don't include arbitrary
 *   files from the source repo in the deployed bundle. JSON files in
 *   apps/web/content/blog/*.json are NOT bundled — the Worker has no
 *   fs access to them at runtime. To make the posts available at
 *   request time, we inline them into a TypeScript module that's
 *   statically imported by lib/blog.ts. TypeScript imports get
 *   bundled by OpenNext's esbuild step.
 *
 * When it runs:
 *   - Automatically before `pnpm opennext:build` (via the package.json
 *     "prebuild" hook — see scripts/blog-daily/../.. /package.json).
 *   - Manually with: node scripts/build-blog-data.mjs
 *
 * Idempotent: re-runs produce a byte-identical output as long as the
 * source JSON files haven't changed.
 */

import { promises as fs } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const REPO_ROOT = path.resolve(__dirname, "..");
const CONTENT_DIR = path.join(REPO_ROOT, "apps", "web", "content", "blog");
const OUT_FILE = path.join(REPO_ROOT, "apps", "web", "lib", "blog-generated-posts.ts");

async function findContentBlogDir() {
  let dir = __dirname;
  for (let depth = 0; depth < 12; depth++) {
    const candidate = path.join(dir, "apps", "web", "content", "blog");
    try {
      await fs.access(candidate);
      return candidate;
    } catch {
      const parent = path.dirname(dir);
      if (parent === dir) break;
      dir = parent;
    }
  }
  throw new Error(`content/blog dir not found from ${__dirname}`);
}

async function main() {
  const contentDir = await findContentBlogDir();

  const files = (await fs.readdir(contentDir))
    .filter((f) => f.endsWith(".json") && !f.startsWith("_"))
    .sort();

  const posts = [];
  for (const file of files) {
    const raw = await fs.readFile(path.join(contentDir, file), "utf-8");
    const post = JSON.parse(raw);
    // Minimal validation
    if (!post.slug || !post.title || !post.sections) {
      console.warn(`[build-blog-data] skipping ${file}: missing required fields`);
      continue;
    }
    posts.push(post);
  }

  // Stable order: newest first by date
  posts.sort((a, b) => (a.date < b.date ? 1 : -1));

  const header = `// ⚠️  AUTO-GENERATED — do not edit by hand.
// Regenerated by scripts/build-blog-data.mjs on every \`pnpm build\`.
// Source: apps/web/content/blog/*.json (one file per post).
// This file is checked in so the deployed Cloudflare Worker can ship
// with the latest posts inlined (Cloudflare Workers don't bundle
// arbitrary JSON files from the repo into the deployed bundle).

import type { BlogPost } from "./blog";

export const GENERATED_POSTS: BlogPost[] =`;

  const body = JSON.stringify(posts, null, 2) + ";\n";

  // Stable serialization: re-write with a header comment that includes
  // a content hash, so a fresh checkout can verify nothing changed.
  const content = `${header} ${body}`;

  // Avoid touching the file if content is byte-identical (faster rebuilds).
  let existing = "";
  try { existing = await fs.readFile(OUT_FILE, "utf-8"); } catch {}
  if (existing === content) {
    console.log(`[build-blog-data] up to date (${posts.length} posts)`);
    return;
  }

  await fs.writeFile(OUT_FILE, content, "utf-8");
  console.log(`[build-blog-data] wrote ${posts.length} posts to ${path.relative(REPO_ROOT, OUT_FILE)}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
